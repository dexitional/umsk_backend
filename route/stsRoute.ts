import { Router } from 'express';
import StsController from '../controller/stsController';
import { STS_ADMIN_ROLES, stsAdmin } from '../util/sts';
const { verifyToken } = require('../middleware/verifyToken');
const { requireRole } = require('../middleware/requireRole');
const router = Router();
const controller = new StsController();
router.use(verifyToken);
router.use((req: any, res, next) => typeof req.userId === 'string' && req.userId.trim() ? next() : res.status(401).json({ message: 'Please sign in again.' }));
router.get('/mine', controller.mine);
router.use((req: any, res, next) => Number(req.groupId) === 2 ? next() : res.status(403).json({ message: 'STS management requires a staff account.' }));
router.use(requireRole([...STS_ADMIN_ROLES, 'sts::mentor']));
const admin = (req: any, res: any, next: any) => stsAdmin(req) ? next() : res.status(403).json({ message: 'Only an STS coordinator can manage schools and placements.' });
router.get('/options', controller.options);
router.get('/students', admin, controller.candidates);
router.post('/schools', admin, controller.saveSchool);
router.patch('/schools/:id', admin, controller.saveSchool);
router.delete('/schools/:id', admin, controller.deleteSchool);
router.post('/mentors', admin, controller.saveMentor);
router.patch('/mentors/:id', admin, controller.saveMentor);
router.delete('/mentors/:id', admin, controller.deleteMentor);
router.get('/assignments', controller.assignments);
router.get('/assignments/:id/history', controller.history);
router.post('/assignments', admin, controller.createAssignment);
router.patch('/assignments/:id', controller.updateAssignment);
router.get('/report', controller.report);
export default router;
